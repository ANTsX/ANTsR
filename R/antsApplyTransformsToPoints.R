#' Apply transforms to points.
#'
#' Apply a transform list to map a pointset from one domain to another. In
#' registration, one computes mappings between pairs of domains.
#' These transforms are often a sequence of increasingly complex maps, e.g.
#' from translation, to rigid, to affine to deformation.  The list of such
#' transforms is passed to this function to interpolate one image domain
#' into the next image domain, as below.  The order matters strongly and the
#' user is advised to familiarize with the standards established in examples.
#' Importantly, point mapping goes the opposite direction of image mapping,
#' for both reasons of convention and engineering.
#'
#' @param dim dimensionality of the transformation.
#' @param points moving point set with n-points in rows of at least dim
#' columns - we maintain extra information in additional columns. this
#' may be either a dataframe or a 2D antsImage - the latter may be better
#' for large pointsets.
#' @param transformlist character vector of transforms generated by
#' antsRegistration where each transform is a filename.
#' @param whichtoinvert vector of booleans, same length as transforms
#' @param precision \code{"float"} (default) or \code{"double"}: the
#' precision used to store and transform the coordinates.  Single precision
#' keeps about 7 significant digits, so use \code{"double"} when coordinates
#' must be exact beyond that (e.g. large physical coordinates).  When
#' \code{precision} is not given and \code{points} is a double antsImage,
#' double precision is used.
#' @return same type as input; an antsImage input is returned with the pixel
#' type given by \code{precision}.  An error is raised if the point set has
#' fewer than \code{dim} coordinate columns or the transformation fails.
#' @author Avants BB
#' @examples
#'
#' fixed <- antsImageRead(getANTsRData("r16"), 2)
#' moving <- antsImageRead(getANTsRData("r64"), 2)
#' fixed <- resampleImage(fixed, c(64, 64), 1, 0)
#' moving <- resampleImage(moving, c(64, 64), 1, 0)
#' mytx <- antsRegistration(
#'   fixed = fixed, moving = moving,
#'   typeofTransform = c("SyN"), verbose = FALSE
#' )
#' pts <- data.frame(
#'   x = c(110.5, 120, 130), y = c(108.1, 121.0, 130),
#'   label = c(1, 2, 3)
#' )
#' wpts <- antsApplyTransformsToPoints(
#'   dim = 2, points = pts,
#'   transformlist = mytx$fwdtransforms
#' )
#' wptsi <- antsApplyTransformsToPoints(
#'   dim = 2, points = wpts,
#'   transformlist = mytx$invtransforms
#' ) # close to pts
#'
#' \dontrun{
#' fixed <- antsImageRead(getANTsRData("r16"), 2)
#' moving <- antsImageRead(getANTsRData("r64"), 2)
#' fpts <- kmeansSegmentation(fixed, 3)$segmentation %>%
#'   thresholdImage(1, 1) %>%
#'   labelClusters(5) %>%
#'   getCentroids(5)
#' wpts <- antsApplyTransformsToPoints(
#'   dim = 2, points = fpts,
#'   transformlist = mytx$fwdtransforms
#' )
#' labimgf <- fixed * 0
#' labimgm <- moving * 0
#' for (p in 1:nrow(wpts))
#' {
#'   pt <- as.numeric(wpts[p, 1:2])
#'   idx <- round(antsTransformPhysicalPointToIndex(moving, pt))
#'   labimgm[idx[1], idx[2]] <- p
#'   pt <- as.numeric(fpts[p, 1:2])
#'   idx <- round(antsTransformPhysicalPointToIndex(fixed, pt))
#'   labimgf[idx[1], idx[2]] <- p
#' }
#' plot(fixed, labimgf %>% iMath("GD", 2))
#' plot(moving, labimgm %>% iMath("GD", 2))
#' }
#'
#' @seealso \code{\link{antsRegistration}}
#' @export antsApplyTransformsToPoints
antsApplyTransformsToPoints <- function(
    dim,
    points,
    transformlist = "",
    whichtoinvert = NA,
    precision = c("float", "double")) {
  # an antsImage of points keeps its own (double) precision unless asked
  if (missing(precision) && is.antsImage(points) &&
    points@pixeltype == "double") {
    precision <- "double"
  }
  precision <- match.arg(precision)
  ttexists <- TRUE
  for (i in 1:length(transformlist))
  {
    if (!file.exists(transformlist[i])) ttexists <- FALSE
  }
  if (ttexists) {
    mytx <- list()
    # If whichtoinvert is NA, guess as antsApplyTransforms does: invert the
    # matrix of an (affine.mat, warp) pair (e.g. invtransforms), else nothing
    if (all(is.na(whichtoinvert))) {
      if (length(transformlist) == 2 &&
        grepl("\\.mat$", transformlist[1]) &&
        !grepl("\\.mat$", transformlist[2])) {
        whichtoinvert <- c(TRUE, FALSE)
      } else {
        whichtoinvert <- rep(FALSE, length(transformlist))
      }
    }
    if (length(whichtoinvert) != length(transformlist)) {
      stop("Transform list and inversion list must be the same length")
    }
    whichtoinvert <- as.logical(whichtoinvert)
    # the native code can crash on an unreadable transform and silently
    # misapplies one of another dimension, so check them in R first
    for (tf in transformlist) {
      .int_checkPointTransform(tf, dim)
    }
    for (i in c(1:length(transformlist)))
    {
      ismat <- grepl("\\.mat$", transformlist[i]) ||
        grepl("\\.txt$", transformlist[i])
      if (whichtoinvert[i] && !ismat) {
        stop(paste("Cannot invert transform ", i, " ( ", transformlist[i],
          " ), because it is not a matrix. ",
          sep = ""
        ))
      }
      if (!whichtoinvert[i]) {
        mytx <- list(mytx, "-t", transformlist[i])
      } else {
        mytx <- list(
          mytx, "-t",
          paste("[", transformlist[i], ",1]", sep = "")
        )
      }
    }
    # the native code reads float or double points depending on
    # --precision, so the point image must have the matching pixel type
    if (!inherits(points, "antsImage")) {
      usepts <- as.antsImage(data.matrix(points), pixeltype = precision)
    } else {
      usepts <- antsImageClone(points, precision)
    }
    if (usepts@dimension != 2) stop("must be 2d antsImage")
    ncoord <- dim(usepts)[2]
    if (ncoord < dim) {
      stop(
        "points has ", ncoord, " column(s) but a ", dim, "D transform needs ",
        "at least ", dim, " coordinate columns (x, y",
        if (dim > 2) ", z", if (dim > 3) ", t", ")"
      )
    }
    pointsout <- antsImageClone(usepts)
    args <- list(d = dim, i = usepts, o = pointsout, unlist(mytx))
    myargs <- .int_antsProcessArguments(c(args))
    for (jj in c(1:length(myargs))) {
      if (!is.na(myargs[jj])) {
        if (myargs[jj] == "-") {
          myargs2 <- rep(NA, (length(myargs) - 1))
          myargs2[1:(jj - 1)] <- myargs[1:(jj - 1)]
          myargs2[jj:(length(myargs) - 1)] <- myargs[(jj + 1):(length(myargs))]
          myargs <- myargs2
        }
      }
    }
    status <- ANTsRCore::AntsApplyTransformsToPoints(c(
      myargs, "-f", 1,
      "--precision", as.integer(precision == "double")
    ))
    # the output starts as a copy of the input, so a failure must not be
    # returned as if it were transformed coordinates
    if (!identical(as.integer(status), 0L)) {
      stop("antsApplyTransformsToPoints failed (status ", status, ")")
    }

    if (inherits(points, "antsImage")) {
      return(pointsout)
    }
    pointsout <- data.frame(as.matrix(pointsout))
    colnames(pointsout) <- colnames(points)
    if (ncol(pointsout) > dim) {
      pointsout[, (dim + 1):ncol(points)] <- points[, (dim + 1):ncol(points)]
    }
    return(pointsout)
  }
  if (!ttexists) {
    stop("transforms may not exist")
  }
}

# Check that a transform file can be read and has dimension `dim` before it
# reaches native code. Linear and composite transforms are read with
# readAntsrTransform(), which raises an R error for unreadable files.
# Displacement fields are images; ITK's header reader can crash on a corrupt
# NIfTI file, so its header is checked in R first.
.int_checkPointTransform <- function(file, dim) {
  isImage <- grepl("\\.(nii|nii\\.gz|nrrd|nhdr|mha|mhd)$", file,
    ignore.case = TRUE)
  if (!isImage) {
    tx <- tryCatch(readAntsrTransform(file), error = function(e) {
      stop("cannot read transform '", file, "': ", conditionMessage(e),
        call. = FALSE)
    })
    if (tx@dimension != dim) {
      stop("transform '", file, "' is ", tx@dimension, "D but dim = ", dim,
        call. = FALSE)
    }
    return(invisible(TRUE))
  }
  if (grepl("\\.nii(\\.gz)?$", file, ignore.case = TRUE) &&
    !.int_isNiftiFile(file)) {
    stop("cannot read displacement field '", file, "': not a NIfTI file",
      call. = FALSE)
  }
  hdr <- tryCatch(antsImageHeaderInfo(file), error = function(e) {
    stop("cannot read displacement field '", file, "': ",
      conditionMessage(e), call. = FALSE)
  })
  if (length(hdr$dimensions) != dim || hdr$nComponents != dim) {
    stop("'", file, "' is not a ", dim, "D displacement field (",
      length(hdr$dimensions), "D image with ", hdr$nComponents,
      " component(s))", call. = FALSE)
  }
  invisible(TRUE)
}

# A NIfTI-1 or NIfTI-2 header starts with its size (348 or 540), in either
# byte order; gzfile() reads both compressed and plain files
.int_isNiftiFile <- function(file) {
  con <- gzfile(file, "rb")
  on.exit(close(con))
  raw4 <- tryCatch(readBin(con, "raw", 4), error = function(e) raw(0))
  if (length(raw4) < 4) {
    return(FALSE)
  }
  sizes <- c(
    readBin(raw4, "integer", size = 4, endian = "little"),
    readBin(raw4, "integer", size = 4, endian = "big")
  )
  any(sizes %in% c(348L, 540L))
}
