test_that("bracket subsetting and getPixels", {
  a <- array(1:20, c(4, 5))
  img <- as.antsImage(a)
  expect_equal(img[2, 3], matrix(a[2, 3]))
  expect_equal(img[1:2, 2:3], a[1:2, 2:3])
  expect_equal(img[2, ], matrix(a[2, ], nrow = 1))
  expect_equal(img[, 3], matrix(a[, 3]))
  expect_equal(img[], a)
  expect_equal(c(img[NULL]), c(a))
  expect_equal(img[img > 15], 16:20)
  expect_equal(img[c(a) > 15], 16:20)
  expect_equal(img[a > 15], 16:20)
  expect_error(img["a"], "logical")
  expect_equal(getPixels(img, 1:2, 1), matrix(a[1:2, 1]))
  expect_length(getPixels(img, NULL, 1), 0)
  expect_length(getPixels(img, 1, NULL), 0)
  expect_error(getPixels(img, "a", 1), "indices")
  expect_error(getPixels(img, 1, "b"), "indices")

  a3 <- array(1:60, c(3, 4, 5))
  img3 <- as.antsImage(a3)
  expect_equal(c(img3[2, 3, 4]), a3[2, 3, 4])
  expect_equal(c(img3[1:2, 1:2, 1]), c(a3[1:2, 1:2, 1]))
  expect_equal(c(img3[2, 3]), c(a3[2, 3, ]))
  expect_length(getPixels(img3, 1, 1, NULL), 0)
  expect_equal(c(getPixels(img3, 1, 1)), c(a3[1, 1, ]))
  expect_error(getPixels(img3, 1, 1, "a"), "indices")
  expect_equal(dim(img3[, , 2]), c(3, 4, 1))

  a4 <- array(1:120, c(2, 3, 4, 5))
  img4 <- as.antsImage(a4)
  expect_equal(c(img4[1, 2, 3, 4]), a4[1, 2, 3, 4])
  expect_equal(c(getPixels(img4, 1, 1, 1)), c(a4[1, 1, 1, ]))
  expect_length(getPixels(img4, 1, 1, 1, NULL), 0)
  expect_error(getPixels(img4, 1, 1, 1, "z"), "indices")
  expect_equal(c(img4[1, 1]), c(a4[1, 1, , ]))
})

test_that("bracket assignment and antsSetPixels", {
  img <- makeImage(c(4, 5), 0)
  img[2, 3] <- 7
  expect_equal(as.array(img)[2, 3], 7)
  img[1, ] <- array(1, c(1, 5))
  expect_equal(as.array(img)[1, ], rep(1, 5))
  img[, 5] <- array(2, c(4, 1))
  expect_equal(as.array(img)[, 5], rep(2, 4))
  img[NULL] <- 3
  expect_true(all(as.array(img) == 3))
  img[as.array(img) == 3 & row(as.array(img)) == 1] <- 4
  expect_equal(as.array(img)[1, ], rep(4, 5))
  m <- img * 0
  m[1, 1] <- 1
  img[m] <- 9
  expect_equal(as.array(img)[1, 1], 9)
  img[c(as.array(img)) == 9] <- 10
  expect_equal(as.array(img)[1, 1], 10)
  lm <- matrix(FALSE, 4, 5)
  lm[4, 4] <- TRUE
  img[lm] <- 11
  expect_equal(as.array(img)[4, 4], 11)
  expect_error(img[matrix(1, 4, 5)] <- 1, "logical")
  la <- array(FALSE, c(4, 5))
  la[3, 3] <- TRUE
  img[la] <- 12
  expect_equal(as.array(img)[3, 3], 12)
  expect_error(img[list(mask = 1)] <- 1, "logical")
  expect_error(img[list(mask = TRUE, region = 1)] <- 1, "antsRegion")

  img2 <- antsSetPixels(makeImage(c(3, 3), 0), 1:2, 2, value = 5)
  expect_equal(as.array(img2)[1:2, 2], c(5, 5))
  img3 <- antsSetPixels(makeImage(c(3, 3, 3), 0), 1, 1, 1:3, value = 2)
  expect_equal(as.array(img3)[1, 1, ], c(2, 2, 2))
  img4 <- antsSetPixels(makeImage(c(2, 2, 2, 2), 0), 1, 1, 1, 2, value = 6)
  expect_equal(as.array(img4)[1, 1, 1, 2], 6)
  expect_error(antsSetPixels(img2, "a", 1, value = 1), "indices")
  expect_error(antsSetPixels(img2, 1, "a", value = 1), "indices")
  expect_error(antsSetPixels(img3, 1, 1, "a", value = 1), "indices")
  expect_error(antsSetPixels(img4, 1, 1, 1, "a", value = 1), "indices")
})

test_that("antsImage class methods: show, coercions, constructors", {
  img <- makeImage(c(2, 3), c(1, 2, 3, 1, 2, 3), spacing = c(2, 2))
  out <- capture.output(show(img))
  expect_true(any(grepl("Pixel Type", out)))
  expect_true(any(grepl("2x3", out)))
  tf <- tempfile(fileext = ".nii.gz")
  on.exit(unlink(tf), add = TRUE)
  antsImageWrite(img, tf)
  rd <- antsImageRead(tf)
  expect_true(any(grepl("Filename", capture.output(show(rd)))))
  m <- img > 1
  expect_equal(as.numeric(img), c(1, 2, 3, 1, 2, 3))
  expect_equal(as.numeric(img, mask = m), c(2, 3, 2, 3))
  expect_equal(as.matrix(img), matrix(c(1, 2, 3, 1, 2, 3), 2))
  expect_equal(c(as.matrix(img, mask = m)), c(2, 3, 2, 3))
  expect_error(as.matrix(makeImage(c(2, 2, 2), 1)), "dimension must be 2")
  expect_error(as.numeric(img, mask = "a"), "binary")
  expect_error(as.array(img, mask = "a"), "binary")
  expect_error(as.matrix(img, mask = "a"), "binary")
  expect_equal(as.character(img), as.character(c(1, 2, 3, 1, 2, 3)))
  expect_equal(levels(as.factor(img)), c("1", "2", "3"))
  expect_equal(levels(ANTsR:::factor.antsImage(img, levels = c("3", "2", "1"))), c("3", "2", "1"))
  expect_equal(ANTsR:::as.matrix.antsImage(img), matrix(c(1, 2, 3, 1, 2, 3), 2))
  expect_error(ANTsR:::as.matrix.antsImage(makeImage(c(2, 2, 2), 1)), "dimension must be 2")
  expect_equal(c(ANTsR:::as.array.antsImage(img, mask = m)), c(2, 3, 2, 3))
  expect_error(ANTsR:::as.matrix.antsImage(img, mask = "a"), "binary")
  expect_error(ANTsR:::as.array.antsImage(img, mask = "a"), "binary")
  ni <- new("antsImage", "float", 2)
  expect_s4_class(ni, "antsImage")
  expect_equal(ni@dimension, 2L)
  ref <- makeImage(c(2, 3), 0, spacing = c(3, 4), origin = c(1, 1))
  am <- as.antsImage(matrix(1:6, 2), reference = ref)
  expect_equal(antsGetSpacing(am), c(3, 4))
  expect_equal(antsGetOrigin(am), c(1, 1))
  aa <- as.antsImage(array(1:24, c(2, 3, 4)), spacing = c(1, 2, 3))
  expect_equal(antsGetSpacing(aa), c(1, 2, 3))
  aa2 <- as.antsImage(array(1:24, c(2, 3, 4)), reference = makeImage(c(2, 3, 4), 0, spacing = c(5, 5, 5)))
  expect_equal(antsGetSpacing(aa2), c(5, 5, 5))
  expect_true(is.antsImage(img))
  expect_false(is.antsImage(1))
})
