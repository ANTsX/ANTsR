mk_img <- function(seed = 1, dims = c(4, 5), lo = 0.1, hi = 0.9) {
  set.seed(seed)
  makeImage(dims, runif(prod(dims), lo, hi), spacing = rep(2, length(dims)), origin = rep(1, length(dims)))
}
arr <- function(x) as.array(x)

test_that("Math group methods match base R on arrays", {
  img <- mk_img()
  a <- arr(img)
  fns <- list(
    abs = abs, sign = sign, sqrt = sqrt, ceiling = ceiling, round = round,
    floor = floor, trunc = trunc, log10 = log10, log2 = log2, acos = acos,
    asin = asin, atan = atan, asinh = asinh, atanh = atanh, cos = cos,
    sin = sin, tan = tan, cosh = cosh, sinh = sinh, tanh = tanh,
    cospi = cospi, sinpi = sinpi, exp = exp, lgamma = lgamma, gamma = gamma,
    digamma = digamma, expm1 = expm1, log1p = log1p
  )
  for (nm in names(fns)) {
    res <- fns[[nm]](img)
    expect_s4_class(res, "antsImage")
    expect_equal(dim(res), dim(img))
    expect_equal(c(arr(res)), c(fns[[nm]](a)), tolerance = 1e-4, info = nm)
  }
  expect_equal(antsGetSpacing(sqrt(img)), c(2, 2))
  expect_equal(c(arr(acosh(img + 1))), c(acosh(a + 1)), tolerance = 1e-4)
  expect_equal(c(arr(log(img))), c(log(a)), tolerance = 1e-4)
  expect_equal(c(arr(log(img, 2))), c(log2(a)), tolerance = 1e-4)
  expect_equal(c(arr(log(img, 10))), c(log10(a)), tolerance = 1e-4)
  expect_equal(c(arr(log(img, 3))), c(log(a, 3)), tolerance = 1e-4)
  expect_equal(c(arr(tanpi(img * 0.4))), c(tanpi(a * 0.4)), tolerance = 1e-3)
  half <- makeImage(c(2, 2), c(0.5, 0.1, 0.2, 0.3))
  expect_warning(tp <- tanpi(half), "tanpi")
  expect_true(is.nan(arr(tp)[1, 1]))
  g <- gamma(makeImage(c(2, 2), c(0, 1, 2, 3)))
  expect_true(is.nan(arr(g)[1, 1]))
  expect_equal(arr(g)[2, 2], 2)
  nimg <- !makeImage(c(2, 2), c(0, 1, 2, 0))
  expect_equal(c(arr(nimg)), c(1, 0, 0, 1))
})

test_that("comparison operators across signatures", {
  img <- mk_img(2)
  img2 <- mk_img(3)
  a <- arr(img)
  a2 <- arr(img2)
  ops <- c("==", ">", "<", "!=", "<=", ">=")
  for (op in ops) {
    f <- get(op)
    expect_equal(c(arr(f(img, img2))), as.numeric(c(f(a, a2))), info = op)
    expect_equal(c(arr(f(img, 0.5))), as.numeric(c(f(a, 0.5))), info = op)
    expect_equal(c(arr(f(img, a2))), as.numeric(c(f(a, a2))), info = op)
    expect_equal(c(arr(f(a2, img))), as.numeric(c(f(a2, a))), info = op)
    expect_equal(c(arr(f(0.5, img))), as.numeric(c(f(0.5, a))), info = op)
    # vector comparison falls back to array arithmetic
    v <- rep(0.5, length(a))
    expect_equal(c(arr(f(img, v))), as.numeric(c(f(a, v))), info = op)
    expect_error(f(img, list(1)), "antsRegions")
    other <- makeImage(c(4, 5), 1)
    expect_error(f(img, other), "physical space")
  }
})

test_that("arithmetic operators across signatures", {
  img <- mk_img(4, lo = 1, hi = 3)
  img2 <- mk_img(5, lo = 1, hi = 3)
  a <- arr(img)
  a2 <- arr(img2)
  ops <- c("+", "-", "*", "/", "^", "%%", "%/%")
  for (op in ops) {
    f <- get(op)
    expect_equal(c(arr(f(img, img2))), c(f(a, a2)), tolerance = 1e-4, info = op)
    expect_equal(c(arr(f(img, 2))), c(f(a, 2)), tolerance = 1e-4, info = op)
    expect_equal(c(arr(f(2, img))), c(f(2, a)), tolerance = 1e-4, info = op)
    expect_equal(c(arr(f(img, a2))), c(f(a, a2)), tolerance = 1e-4, info = op)
    expect_equal(c(arr(f(a2, img))), c(f(a2, a)), tolerance = 1e-4, info = op)
    expect_equal(c(arr(f(img, TRUE))), c(f(a, 1)), tolerance = 1e-4, info = op)
    expect_equal(c(arr(f(TRUE, img))), c(f(1, a)), tolerance = 1e-4, info = op)
    expect_error(f(img, list(1)), "antsRegions")
    expect_error(f(list(1), img), "antsRegions")
    expect_error(f(img, makeImage(c(4, 5), 1)), "physical space")
  }
  expect_equal(c(arr(-img)), c(-a), tolerance = 1e-5)
  expect_equal(antsGetOrigin(img + img2), c(1, 1))
})

test_that("logic operators", {
  b1 <- makeImage(c(2, 3), c(0, 1, 0, 1, 1, 0))
  b2 <- makeImage(c(2, 3), c(1, 1, 0, 0, 1, 0))
  x1 <- c(arr(b1)) != 0
  x2 <- c(arr(b2)) != 0
  expect_equal(c(arr(b1 & b2)), as.numeric(x1 & x2))
  expect_equal(c(arr(b1 | b2)), as.numeric(x1 | x2))
  u1 <- antsImageClone(b1, "unsigned char")
  u2 <- antsImageClone(b2, "unsigned char")
  expect_equal(c(arr(u1 & u2)), as.numeric(x1 & x2))
  expect_equal(c(arr(u1 | u2)), as.numeric(x1 | x2))
  expect_equal(c(arr(b1 & TRUE)), as.numeric(x1))
  expect_equal(c(arr(b1 | FALSE)), as.numeric(x1))
  expect_equal(c(arr(u1 & TRUE)), as.numeric(x1))
  expect_equal(c(arr(u1 | TRUE)), rep(1, 6))
  expect_equal(c(arr(TRUE & b1)), as.numeric(x1))
  expect_equal(c(arr(b1 & 1)), as.numeric(x1))
  expect_equal(c(arr(0 | b1)), as.numeric(x1))
  m2 <- arr(b2)
  expect_equal(c(arr(b1 & m2)), as.numeric(x1 & x2))
  expect_equal(c(arr(m2 | b1)), as.numeric(x1 | x2))
  expect_error(b1 & list(1), "antsRegions")
  expect_error(list(1) | b1, "antsRegions")
  expect_error(b1 & makeImage(c(2, 3), 1, spacing = c(3, 3)), "physical space")
  expect_error(b1 | makeImage(c(2, 3), 1, spacing = c(3, 3)), "physical space")
  expect_error(b1 & "TRUE", "operations are possible")
  # Math group fallback: cumsum drops dims, so re-wrapping as an image fails
  expect_error(cumsum(b1), "as.antsImage")
})

test_that("finite checks, which and summaries", {
  img <- makeImage(c(2, 3), c(1, NA, 3, Inf, NaN, -2))
  expect_equal(c(arr(is.na(img))), c(0, 1, 0, 0, 1, 0))
  expect_true(anyNA(img))
  expect_false(anyNA(makeImage(c(2, 2), 1)))
  # NA is stored as NaN in a float image
  expect_equal(c(arr(is.nan(img))), c(0, 1, 0, 0, 1, 0))
  expect_equal(c(arr(is.infinite(img))), c(0, 0, 0, 1, 0, 0))
  expect_equal(c(arr(is.finite(img))), c(1, 0, 1, 0, 0, 1))
  b <- makeImage(c(2, 3), c(0, 1, 0, 1, 1, 0))
  expect_equal(which(b), c(2, 4, 5))
  expect_equal(nrow(which(b, arr.ind = TRUE)), 3)

  v <- makeImage(c(2, 3), c(1, 2, 3, 4, 5, 6))
  m <- makeImage(c(2, 3), c(1, 1, 1, 0, 0, 0))
  expect_equal(max(v), 6)
  expect_equal(min(v), 1)
  expect_equal(max(v, mask = m), 3)
  expect_equal(min(v, mask = m), 1)
  expect_equal(range(v), c(1, 6))
  expect_equal(sum(v), 21)
  expect_equal(prod(v), 720)
  expect_equal(sum(v, mask = m), 6)
  expect_true(suppressWarnings(any(v > 5)))
  expect_false(suppressWarnings(all(v > 5)))
  expect_equal(mean(v), 3.5)
  expect_equal(mean(v, mask = m), 2)
  expect_equal(median(v), 3.5)
  expect_equal(median(v, mask = m), 2)
  expect_equal(sort(unique(v, mask = m)), c(1, 2, 3))
  expect_equal(sd(v), sd(1:6), tolerance = 1e-6)
  expect_equal(var(v), var(1:6), tolerance = 1e-6)
  expect_equal(var(v, mask = m), 1, tolerance = 1e-6)
  expect_equal(ANTsR:::sd.default(c(1, 2, 3)), 1)
  expect_equal(ANTsR:::var.default(c(1, 2, 3)), 1)
})

